'use strict';

/**
 * 保护率域的共用派生量（CELL_REGISTRY.md §8 F1）。
 *
 * 本文件目前只供两格用：
 *   · D32「资产覆盖率」
 *   · D33「威胁遏制率」
 * 两格都是**常量格**：用户口径 2026-10-13「D32 是资产覆盖率、D33 是威胁遏制率，**默认写 100%**」
 * —— 报告里这两格不由任何一份总表算出来，写的就是那个默认值。模板上它们旁边本来就写着
 * 「默认100%」（E33），本文件只是把这个默认值落成可取用的形态。
 *
 * ⚠️ 为什么是「一个具名常量 + 两条各自的 compute」，而不是 D33 写 `alias: 'D32'`（H5）：
 * 那两个 100% **不是一个量写到两个地址**，是两个各自独立的指标各自取默认值 ——
 * 用户投喂里 D32 与 D33 是两条口径（资产覆盖率 / 威胁遏制率），今天恰好都落在 100% 上。
 * 真去 alias，哪天其中一格拿到真实算法（比如威胁遏制率改按事件表算），另一格会被一起改掉，
 * 而用户从没说过这两格必须同进同退 —— 那正是 H5 想避免的反面。
 * H4 要求的那件事（同一个量只定义一次）在这里由本文件的具名常量保证：
 * 两条 compute 引的是同一个 `DEFAULT_PROTECTION_RATE`，谁都没有重抄那个 1。
 *
 * ⚠️ 本文件的函数**不读 ctx**（H3：compute 是纯函数、只读 ctx —— 这里是读了 0 个字段）：
 * 常量格没有数据源，也就没有"缺数"这一档，它永远落值。这与「接口不通写『接口不通无值』」
 * 那条长期口径无关（那一档属于靠接口取数的格子，见 stats/context.js 的 UNAVAILABLE_TEXT）。
 */

/**
 * 「默认 100%」这个默认值本身 —— 小数形式 **1**（= 100%）。
 *
 * ⚠️ 是**小数 1**，不是字符串 `'100%'`、也不是数字 `100`：两格都按 `mode: 'percent'` 落值
 * （CELL_REGISTRY.md §4），写层（scripts/build_report.py 的 apply_statistics_writes）
 * 会给小数配上 `'0.00%'` 数字格式 —— 所以报告里**显示**的是 `100.00%`、
 * 单元格里**存**的是 1，下游要拿它做算术不必先剥百分号。
 * 用户口径 2026-10-13（投喂时对这三种落法的选择）：按仓库里「率 / 占比」一贯的 percent 模式写。
 */
const DEFAULT_PROTECTION_RATE = 1;

/**
 * 保护率格的默认取值 —— D32 / D33 共用的这一个常量（H4）。
 *
 * 之所以包一层函数而不是让两条 compute 直接写 `() => 1`：那样就成了两处各自硬编码的常数，
 * 改默认值要改两处、且没有任何地方写着"这两格共用一个默认口径"（与 H4 要消灭的状态同类）。
 *
 * @returns {number} 1（= 100%；写层再套 `'0.00%'` 格式）
 */
function defaultProtectionRate() {
  return DEFAULT_PROTECTION_RATE;
}

module.exports = {
  DEFAULT_PROTECTION_RATE,
  defaultProtectionRate
};
