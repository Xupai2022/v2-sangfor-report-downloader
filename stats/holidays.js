/** 表覆盖范围（闭区间，`YYYY-MM-DD`）。越界的报告期由 importantPeriods 抛错。 */
const COVERAGE_START = '2025-01-01';
const COVERAGE_END = '2028-12-31';

const DATE_ONLY = /^\d{4}-\d{2}-\d{2}$/;

/**
 * 模块加载即校验表本身是否自洽 —— 表是手维护的年度数据，写错一个字就全错。
 *
 * 校验四件事：日期形态、起止顺序、升序、**两两不重叠**。
 * 最后一条是刻意的：它钉住「2025 国庆中秋按官方合并成一条」这个口径，
 * 谁再拆回老仓库那种重叠写法，require 就当场炸。
 */
function assertTableSane(holidays) {
  let previous = null;

  holidays.forEach((holiday, index) => {
    const at = `stats/holidays.js HOLIDAYS[${index}]`;

    if (!holiday || typeof holiday.name !== 'string' || !holiday.name) {
      throw new Error(`${at} 缺 name: ${JSON.stringify(holiday)}`);
    }
    if (!DATE_ONLY.test(holiday.start) || !DATE_ONLY.test(holiday.end)) {
      throw new Error(`${at}（${holiday.name}）起止必须是 YYYY-MM-DD: ${holiday.start} ~ ${holiday.end}`);
    }
    if (holiday.source !== OFFICIAL && holiday.source !== INFERRED) {
      throw new Error(`${at}（${holiday.name}）source 只能是 '${OFFICIAL}' 或 '${INFERRED}': ${holiday.source}`);
    }
    if (holiday.start > holiday.end) {
      throw new Error(`${at}（${holiday.name}）起止倒置: ${holiday.start} > ${holiday.end}`);
    }
    if (holiday.start < COVERAGE_START || holiday.end > COVERAGE_END) {
      throw new Error(
        `${at}（${holiday.name}）超出覆盖范围 ${COVERAGE_START} ~ ${COVERAGE_END}: ${holiday.start} ~ ${holiday.end}`
      );
    }
    if (previous && holiday.start <= previous.end) {
      throw new Error(
        `${at}（${holiday.name} ${holiday.start}~${holiday.end}）与上一条`
        + `（${previous.name} ${previous.start}~${previous.end}）重叠或未按 start 升序 —— `
        + '放假整段两两不重叠、按时间升序，见本文件头注（2025 国庆中秋按官方原文合并为一条）'
      );
    }

    previous = holiday;
  });
}

assertTableSane(HOLIDAYS);

